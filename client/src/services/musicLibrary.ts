interface ITunesTrack {
  trackId: number;
  trackName: string;
  artistName: string;
  collectionName?: string;
  artworkUrl100: string;
  previewUrl: string;
  trackTimeMillis: number;
}

export async function searchSongs(query: string): Promise<MediaItemInput[]> {
  const clean = query.trim();
  if (!clean) return CURATED_TRACKS;

  try {
    const url = `https://itunes.apple.com/search?term=${encodeURIComponent(
      clean
    )}&entity=song&limit=25`;
    const res = await fetch(url);
    if (!res.ok) throw new Error('Search failed');

    const data = (await res.json()) as { results?: ITunesTrack[] };
    const results = data.results || [];

    const items: MediaItemInput[] = results
      .filter((t) => Boolean(t.previewUrl && t.trackName))
      .map((t) => {
        const hdArtwork = t.artworkUrl100
          ? t.artworkUrl100.replace('100x100bb', '600x600bb')
          : '';
        return {
          provider: 'audio' as const,
          sourceType: 'track' as const,
          mediaId: String(t.trackId),
          url: t.previewUrl,
          title: t.trackName,
          artist: t.artistName || 'Unknown Artist',
          album: t.collectionName || '',
          thumbnail: hdArtwork,
          duration: Math.max(30, Math.round((t.trackTimeMillis || 30000) / 1000)),
          isPlayable: true,
        };
      });

    return items;
  } catch (err) {
    console.warn('iTunes search failed, filtering curated tracks', err);
    return CURATED_TRACKS.filter(
      (t) =>
        t.title.toLowerCase().includes(clean.toLowerCase()) ||
        t.artist.toLowerCase().includes(clean.toLowerCase())
    );
  }
}

export function extractYouTubeId(url: string): string | null {
  const clean = url.trim();
  const match =
    clean.match(/(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|watch\?.+&v=))([\w-]{11})/) ||
    clean.match(/^([\w-]{11})$/);
  return match ? match[1] : null;
}

export function extractSpotifyId(url: string): string | null {
  const clean = url.trim();
  const match = clean.match(/spotify(?:\.com)?(?:\/track|\:track)[\/:]([a-zA-Z0-9]{22})/);
  return match ? match[1] : null;
}

export async function resolveDirectMedia(url: string): Promise<MediaItemInput> {
  const clean = url.trim();

  // 1. YouTube
  const ytId = extractYouTubeId(clean);
  if (ytId) {
    let title = 'YouTube Video';
    let author = 'YouTube';
    let thumbnail = `https://img.youtube.com/vi/${ytId}/hqdefault.jpg`;

    try {
      const res = await fetch(
        `https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${ytId}&format=json`
      );
      if (res.ok) {
        const meta = (await res.json()) as { title?: string; author_name?: string; thumbnail_url?: string };
        if (meta.title) title = meta.title;
        if (meta.author_name) author = meta.author_name;
        if (meta.thumbnail_url) thumbnail = meta.thumbnail_url;
      }
    } catch {
      // Use fallback defaults
    }

    return {
      provider: 'youtube',
      sourceType: 'video',
      mediaId: ytId,
      url: `https://www.youtube.com/watch?v=${ytId}`,
      title,
      artist: author,
      thumbnail,
      duration: 240,
      isPlayable: true,
    };
  }

  // 2. Spotify
  const spId = extractSpotifyId(clean);
  if (spId) {
    let title = 'Spotify Track';
    let thumbnail = '';

    try {
      const res = await fetch(
        `https://open.spotify.com/oembed?url=https://open.spotify.com/track/${spId}`
      );
      if (res.ok) {
        const meta = (await res.json()) as { title?: string; thumbnail_url?: string };
        if (meta.title) title = meta.title;
        if (meta.thumbnail_url) thumbnail = meta.thumbnail_url;
      }
    } catch {
      // Fallback
    }

    return {
      provider: 'spotify',
      sourceType: 'track',
      mediaId: spId,
      url: `https://open.spotify.com/track/${spId}`,
      title,
      artist: 'Spotify',
      thumbnail,
      duration: 210,
      isPlayable: true,
    };
  }

  // 3. Direct Audio URL
  try {
    const parsed = new URL(clean.startsWith('http') ? clean : `https://${clean}`);
    const filename = parsed.pathname.split('/').pop() || 'Audio Track';
    const cleanTitle = decodeURIComponent(filename).replace(/\.[a-z0-9]+$/i, '');

    return {
      provider: 'audio',
      sourceType: 'url',
      mediaId: `audio_${Date.now()}`,
      url: parsed.href,
      title: cleanTitle || 'Direct Audio Stream',
      artist: parsed.hostname,
      thumbnail: '',
      duration: 180,
      isPlayable: true,
    };
  } catch {
    throw new Error('Please enter a valid YouTube, Spotify, or audio URL.');
  }
}

